#!/usr/bin/env python3
"""Does the retrained head only know what Unsplash looks like?

The blind spot in leave-generators-out
--------------------------------------
That test varies the AI side and shows the head handles unseen generators
(mean AUC 0.9593). But every REAL image in every fold came from Unsplash Lite —
one source, one aesthetic, professional photography. So the head could be
scoring "looks like a stock photo" rather than "shows no generation artefacts",
and the generator test would never notice.

That shortcut would be fatal: the bounty's real class is "web-realistic", not
stock photography. If the head has learned Unsplash, it will flag ordinary web
images as AI.

This test
---------
Score REAL images the head has never seen and that look nothing like Unsplash:
programmatically drawn charts, UI mockups, text documents and logos (non-AI by
construction, generated by make_synthetic_real_set.py). Every score above the
threshold is a false positive.

Compares the retrained head against the original head on the same images, so
the question is not "is it perfect" but "is it worse than what we already ship".

Usage:
    python test_head_on_unseen_reals.py
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

DEFAULT_DATA_DIR = Path(__file__).resolve().parent / "data"


def main() -> int:
    import logging
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s",
                        datefmt="%H:%M:%S")
    log = logging.getLogger("unseen_reals")

    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--model", default="OwensLab/commfor-model-224")
    p.add_argument("--input-size", type=int, default=224)
    p.add_argument("--head", type=Path,
                   default=Path(__file__).resolve().parent / "robust_head.json")
    p.add_argument("--set-dir", type=Path, default=DEFAULT_DATA_DIR / "synthetic_real")
    p.add_argument("--threshold", type=float, default=0.65)
    args = p.parse_args()

    import torch
    from run_inference_commfor import load_model
    from train_robust_head import extract_features

    if not args.head.exists():
        print(f"ERROR: {args.head} not found — run train_robust_head.py first",
              file=sys.stderr)
        return 1
    hd = json.loads(args.head.read_text(encoding="utf-8"))
    W = torch.tensor(hd["weights"], dtype=torch.float32)
    b = float(hd["bias"])
    mu = torch.tensor(hd["feature_mean"], dtype=torch.float32)
    sd = torch.tensor(hd["feature_std"], dtype=torch.float32)

    model, _ = load_model(args.model, device="cpu")
    model.eval()

    rows = list(csv.DictReader(open(args.set_dir / "labels.csv", newline="",
                                    encoding="utf-8")))
    log.info("Scoring %d non-Unsplash REAL images from %s",
             len(rows), args.set_dir.name)

    # Original head scores (unmodified model) — the ship-today baseline.
    orig = {}
    with torch.no_grad():
        from PIL import Image
        from run_inference_commfor import build_transform
        tf = build_transform(args.input_size)
        for start in range(0, len(rows), 16):
            chunk = rows[start : start + 16]
            tens, ids = [], []
            for r in chunk:
                with Image.open(args.set_dir / r["filepath"]) as im:
                    tens.append(tf(im.convert("RGB")))
                ids.append(r["image_id"])
            out = model(torch.stack(tens)).reshape(-1)
            for i, v in zip(ids, torch.sigmoid(out).tolist()):
                orig[i] = v

    # Retrained head scores, from the same backbone features.
    X, _, ids = extract_features(model, rows, args.set_dir, args.input_size, 16, log)
    with torch.no_grad():
        z = (((X - mu) / sd) * W).sum(1) + b
        new = dict(zip(ids, torch.sigmoid(z).tolist()))

    by_class_new: dict[str, list] = defaultdict(list)
    by_class_orig: dict[str, list] = defaultdict(list)
    for r in rows:
        cls = r["generator"]
        if r["image_id"] in new:
            by_class_new[cls].append(new[r["image_id"]])
        if r["image_id"] in orig:
            by_class_orig[cls].append(orig[r["image_id"]])

    t = args.threshold
    print("\n" + "=" * 70)
    print(f"FALSE POSITIVES on REAL images that look nothing like Unsplash (t={t})")
    print("=" * 70)
    print(f"  {'class':<18} {'n':>4}  {'ORIGINAL head':>16}  {'RETRAINED head':>16}")

    tot_n = tot_o = tot_r = 0
    for cls in sorted(by_class_new):
        vn, vo = by_class_new[cls], by_class_orig[cls]
        fo = sum(1 for x in vo if x >= t)
        fr = sum(1 for x in vn if x >= t)
        tot_n += len(vn); tot_o += fo; tot_r += fr
        print(f"  {cls:<18} {len(vn):>4}  {fo:>6} ({fo/len(vo):.0%})     "
              f"{fr:>6} ({fr/len(vn):.0%})")

    print("-" * 70)
    print(f"  {'OVERALL':<18} {tot_n:>4}  {tot_o:>6} ({tot_o/tot_n:.0%})     "
          f"{tot_r:>6} ({tot_r/tot_n:.0%})")
    print("=" * 70)

    if tot_r <= tot_o:
        print("\nThe retrained head is NO WORSE than the original on real images")
        print("it has never seen. It did not simply learn 'Unsplash = real'.")
    else:
        extra = tot_r - tot_o
        print(f"\nWARNING: the retrained head flags {extra} MORE non-Unsplash real")
        print("images than the original. It has partly learned the Unsplash")
        print("aesthetic as its notion of 'real', which will not hold on the")
        print("private benchmark's web-realistic images.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
